public class Basics {
    public static void main(String[] args) {
        int statusCode = 404; // int: whole numbers, like an HTTP status code
        double responseTime = 3.2; // double: numbers with decimals, like seconds
        boolean isLoggedIn = false; // boolean: only true or false
        char grade = 'F'; // char: a single character in single quotes
        String username = "admin"; // String: text in double quotes

        System.out.println("Status code: " + statusCode);
        System.out.println("Response time: " + responseTime);
        System.out.println("Is logged in: " + isLoggedIn);
        System.out.println("Grade: " + grade);
        System.out.println("Username: " + username);
    }
}
